"""Play the neural simulators locally (pygame + onnxruntime, CPU). The source environments are
never executed: every frame is generated by the model from its own previous prediction.

    python play.py carla        [--seed 0] [--fps 20] [--scale 6]
    python play.py tinyskies    [--fps 15] [--scale 6]

Keys:  W/Up throttle (forward)   S/Down brake   A/D or Left/Right steer (turn)
       N / P next / previous seed   R reset   ESC quit

The side panel shows what the model predicts besides pixels. For CARLA that is speed, acceleration,
forward and lateral velocity (decoded from the predicted telemetry), the predicted route waypoints
in the ego frame, and the norm of the predicted LiDAR latent. The HUD shows frame rate and model
time per step. Default rates match the training data: CARLA 20 Hz, TinySkies about 7.5 fps
nominal (15 by default for smoother play; simulated time then runs about 2x faster).
"""

import argparse
import json
import time
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent
PANEL_W = 260
CONTROL_RAMP_S = 0.5  # the browser demo ramps keyboard controls over 500 ms for driving


def _keys(pygame):
    k = pygame.key.get_pressed()
    return {
        "up": k[pygame.K_w] or k[pygame.K_UP],
        "down": k[pygame.K_s] or k[pygame.K_DOWN],
        "left": k[pygame.K_a] or k[pygame.K_LEFT],
        "right": k[pygame.K_d] or k[pygame.K_RIGHT],
    }


class Ramp:
    """Keyboard input is binary; ramp each key from 0 to 1 over CONTROL_RAMP_S (as in the browser)."""

    def __init__(self, seconds):
        self.seconds, self.since = seconds, {}

    def __call__(self, name, down, now):
        if not down:
            self.since.pop(name, None)
            return 0.0
        start = self.since.setdefault(name, now)
        return 1.0 if self.seconds <= 0 else min(1.0, (now - start) / self.seconds)


class CarlaGame:
    title = "Neural Simulator — CARLA (world_v3)"

    def __init__(self):
        from carla_sim.runtime import CarlaSimulator, load_browser_seeds

        self.sim, self.seeds, self.ramp = CarlaSimulator(threads=2), load_browser_seeds(), Ramp(CONTROL_RAMP_S)
        self.n = len(self.seeds["labels"])

    def reset(self, i):
        i %= self.n
        s = self.seeds
        self.sim.reset(*(s[k][i : i + 1] for k in ("vision", "lidar", "telemetry", "waypoints")))
        self.label = s["labels"][i]
        return self.sim.state["vision"][0]

    def step(self, keys, now):
        throttle = self.ramp("up", keys["up"], now)
        brake = self.ramp("down", keys["down"], now)
        steer = self.ramp("right", keys["right"], now) - self.ramp("left", keys["left"], now)
        self.controls = np.array([[throttle, brake, steer]], np.float32)
        return self.sim.step(self.controls)["vision"][0]

    def panel(self, pygame, surf, font):
        from carla_sim.model import speed_mps

        st = self.sim.state
        tel = st["telemetry"][0]
        lines = [
            ("seed", self.label.split(".")[0][-15:] + ":" + self.label.split(":")[-1]),
            ("speed", f"{float(speed_mps(tel)) * 3.6:6.1f} km/h"),
            ("accel", f"{float(np.arctanh(np.clip(tel[2], -0.999, 0.999)) * 5):6.2f} m/s²"),
            ("v forward", f"{float(np.arctanh(np.clip(tel[3], -0.999, 0.999)) * 20):6.2f} m/s"),
            ("v lateral", f"{float(np.arctanh(np.clip(tel[4], -0.999, 0.999)) * 20):6.2f} m/s"),
            ("|LiDAR latent|", f"{float(np.linalg.norm(st['lidar_latent'][0])):6.2f}"),
            ("throttle/brake/steer", " ".join(f"{v:+.2f}" for v in self.controls[0])),
        ]
        y = 10
        for k, v in lines:
            surf.blit(font.render(k, True, (140, 140, 135)), (12, y))
            surf.blit(font.render(v, True, (240, 240, 235)), (12, y + 16))
            y += 40
        # Predicted route waypoints, ego frame (x forward, y right): (x/d, y/d, d/50) -> metres.
        wp = st["waypoints"][0]
        d = wp[:, 2] * 50.0
        xs, ys = wp[:, 0] * d, wp[:, 1] * d
        box = pygame.Rect(12, y + 6, PANEL_W - 24, PANEL_W - 24)
        pygame.draw.rect(surf, (60, 60, 58), box, 1)
        surf.blit(font.render("predicted route (50 m)", True, (140, 140, 135)), (12, y - 10))
        cx, by = box.centerx, box.bottom - 6
        scale = (box.height - 12) / 50.0
        for x, yy in zip(xs, ys):
            pygame.draw.circle(surf, (27, 175, 122), (int(cx + yy * scale), int(by - x * scale)), 3)
        pygame.draw.polygon(surf, (235, 104, 52), [(cx, by - 8), (cx - 5, by + 2), (cx + 5, by + 2)])


class TinySkiesGame:
    title = "Neural Simulator — TinySkies (latent sim v1)"

    def __init__(self):
        from PIL import Image

        from tinyskies.runtime import TinySkiesSimulator

        self.sim, self.ramp = TinySkiesSimulator(threads=2), Ramp(0.0)
        root = ROOT / "samples/tinyskies/browser_seeds/session_0005"
        rows = [json.loads(l) for l in (root / "samples.jsonl").read_text().splitlines() if l.strip()]
        self.frames = [
            np.asarray(Image.open(root / "frames" / Path(r["frame_path"]).name).convert("RGB").resize((96, 96), Image.BILINEAR), np.float32) / 255.0
            for r in rows
        ]
        self.n = len(self.frames)

    def reset(self, i):
        i %= self.n
        self.label = f"session_0005 seed {i + 1}/{self.n}"
        z = self.sim.reset(self.frames[i][None])
        return self.sim.decode(z)[0]

    def step(self, keys, now):
        fwd, brake = float(keys["up"]), float(keys["down"])
        turn = float(keys["right"]) - float(keys["left"])
        self.controls = np.array([[fwd, brake, turn]], np.float32)
        return self.sim.decode(self.sim.step(self.controls))[0]

    def panel(self, pygame, surf, font):
        z = self.sim.latents[0, -1]
        dz = np.abs(self.sim.latents[0, -1] - self.sim.latents[0, -2]).mean(-1)
        lines = [
            ("seed", self.label),
            ("forward/brake/turn", " ".join(f"{v:+.0f}" for v in self.controls[0])),
            ("|latent|", f"{float(np.linalg.norm(z)):7.2f}"),
            ("latent change / step", f"{float(dz.mean()):7.4f}"),
        ]
        y = 10
        for k, v in lines:
            surf.blit(font.render(k, True, (140, 140, 135)), (12, y))
            surf.blit(font.render(v, True, (240, 240, 235)), (12, y + 16))
            y += 40
        surf.blit(font.render("per-cell latent change (6x6)", True, (140, 140, 135)), (12, y))
        cell = (PANEL_W - 24) // 6
        peak = max(float(dz.max()), 1e-6)
        for r in range(6):
            for c in range(6):
                v = int(255 * min(1.0, float(dz[r, c]) / peak))
                pygame.draw.rect(surf, (v // 3, v // 2, v), (12 + c * cell, y + 20 + r * cell, cell - 2, cell - 2))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("env", choices=["carla", "tinyskies"])
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--fps", type=float)
    parser.add_argument("--scale", type=int, default=6)
    args = parser.parse_args()

    import pygame

    game = CarlaGame() if args.env == "carla" else TinySkiesGame()
    fps = args.fps or (20.0 if args.env == "carla" else 15.0)
    size = 96 * args.scale
    pygame.init()
    screen = pygame.display.set_mode((size + PANEL_W, size))
    pygame.display.set_caption(game.title)
    font = pygame.font.SysFont("menlo,consolas,monospace", 13)
    clock = pygame.time.Clock()

    seed = args.seed
    frame = game.reset(seed)
    game.controls = np.zeros((1, 3), np.float32)
    step_ms, frames = 0.0, 0
    running = True
    while running:
        for event in pygame.event.get():
            if event.type == pygame.QUIT or (event.type == pygame.KEYDOWN and event.key == pygame.K_ESCAPE):
                running = False
            elif event.type == pygame.KEYDOWN and event.key in (pygame.K_n, pygame.K_p, pygame.K_r):
                seed += {pygame.K_n: 1, pygame.K_p: -1, pygame.K_r: 0}[event.key]
                frame, frames = game.reset(seed), 0

        t = time.perf_counter()
        frame = game.step(_keys(pygame), time.perf_counter())
        step_ms = 0.9 * step_ms + 0.1 * (time.perf_counter() - t) * 1000 if frames else (time.perf_counter() - t) * 1000
        frames += 1

        img = (np.clip(frame, 0, 1) * 255).astype(np.uint8)
        surf = pygame.surfarray.make_surface(img.swapaxes(0, 1))
        screen.blit(pygame.transform.smoothscale(surf, (size, size)), (0, 0))
        panel = pygame.Surface((PANEL_W, size))
        panel.fill((26, 26, 25))
        game.panel(pygame, panel, font)
        hud = f"fps {clock.get_fps():4.1f}  model {step_ms:5.1f} ms  step {frames}"
        panel.blit(font.render(hud, True, (237, 161, 0)), (12, size - 24))
        screen.blit(panel, (size, 0))
        pygame.display.flip()
        clock.tick(fps)
    pygame.quit()


if __name__ == "__main__":
    main()
